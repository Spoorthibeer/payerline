export function patientDocuments(language: Language): string[] {
  return [...patientText[language].documentLabels];
}

export function patientMissingLabel(language: Language, finding: string, procedure: string): string {
  const text = patientText[language].missingLabels;
  const value = finding.toLowerCase();
  if (value.includes("pre-authorisation")) return text.preAuthorizationForm;
  if (value.includes("ecard") || value.includes("e-card") || value.includes("ayushman")) return text.insurerCard;
  if (value.includes("aadhaar") || value.includes("identity")) return text.identityProof;
  if (value.includes("policy")) return text.policyCopy;
  if (value.includes("admission advice")) return text.admissionAdvice;
  if (value.includes("letterhead") || value.includes("dated")) return text.datedLetterhead;
  if (value.includes("matching laboratory")) return text.matchingReports;
  if (value.includes("cbc")) return text.cbc;
  if (value.includes("investigation") || value.includes("laboratory")) return text.investigationReports;
  if (value.includes("fitness")) return text.fitnessCertificate;
  if (value.includes("consent")) return text.signedSurgicalConsent;
  if (value.includes("estimate")) return text.itemisedEstimate;
  if (value.includes("package")) return text.package(procedure);
  return text.other;
}
